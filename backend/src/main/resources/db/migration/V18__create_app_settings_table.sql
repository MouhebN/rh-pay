CREATE TABLE app_settings (
    id BIGSERIAL PRIMARY KEY,
    company_name VARCHAR(150) NOT NULL,
    company_address VARCHAR(255),
    company_email VARCHAR(120),
    company_phone VARCHAR(50),
    work_start_time TIME NOT NULL,
    work_end_time TIME NOT NULL,
    expected_daily_hours NUMERIC(5,2) NOT NULL,
    monthly_reference_hours NUMERIC(6,2) NOT NULL,
    default_annual_leave_days NUMERIC(5,2) NOT NULL,
    allow_negative_leave_balance BOOLEAN NOT NULL DEFAULT FALSE,
    overtime_multiplier NUMERIC(5,2) NOT NULL,
    deduct_late_minutes_from_salary BOOLEAN NOT NULL DEFAULT FALSE,
    currency VARCHAR(10) NOT NULL,
    updated_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_app_settings_updated_by FOREIGN KEY (updated_by_id) REFERENCES users(id),
    CONSTRAINT ck_app_settings_expected_daily_hours CHECK (expected_daily_hours > 0),
    CONSTRAINT ck_app_settings_monthly_reference_hours CHECK (monthly_reference_hours > 0),
    CONSTRAINT ck_app_settings_default_annual_leave_days CHECK (default_annual_leave_days >= 0),
    CONSTRAINT ck_app_settings_overtime_multiplier CHECK (overtime_multiplier >= 1),
    CONSTRAINT ck_app_settings_work_time CHECK (work_start_time < work_end_time)
);

